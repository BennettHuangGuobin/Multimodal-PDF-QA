"""Create a three-page synthetic fixture for local CLI demonstrations."""

import argparse
from pathlib import Path

import pymupdf


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("data/input/demo.pdf"))
    args = parser.parse_args()
    if args.output.exists():
        parser.error(f"Refusing to overwrite an existing file: {args.output}")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with pymupdf.open() as doc:
        doc.set_metadata({"title": "Synthetic PDF preparation demo", "author": "Local test"})
        for number in range(1, 4):
            page = doc.new_page(width=360, height=480)
            page.insert_text((30, 50), f"Synthetic demo - PDF page {number}", fontsize=16)
            page.insert_text((30, 80), "No OCR results are generated by this demo.", fontsize=11)
            page.draw_rect(pymupdf.Rect(30, 120, 180, 260), color=(0.1, 0.3, 0.6),
                           fill=(0.8, 0.9, 1.0))
            if number == 3:
                page.set_rotation(90)
        doc.save(args.output)
    print(args.output)


if __name__ == "__main__":
    main()
